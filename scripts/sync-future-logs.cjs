/* Periodic, read-only pull from the official PCBL game-log bridge.
 * Only validated future games are snapshotted; S1–S3 are never rewritten.
 */
const fs=require('node:fs'),path=require('node:path');
const ROOT=path.resolve(__dirname,'..'),PUBLIC=path.join(ROOT,'public');
const parser=require(path.join(PUBLIC,'live-log-parser.js'));
const future=require(path.join(PUBLIC,'future-stats.js'));
const play=require(path.join(PUBLIC,'play-database.js'));
const savedJson=path.join(PUBLIC,'future-game-logs.json'),savedJs=path.join(PUBLIC,'future-game-logs.js');
const sort=(a,b)=>Number(a.season.slice(1))-Number(b.season.slice(1))||
 ({regular:0,wild_card:1,championship:2}[a.stage]-{regular:0,wild_card:1,championship:2}[b.stage])||a.number-b.number;
function render(games){
 const data=JSON.stringify(games,null,2);
 return {json:data+'\n',js:
  '/* Generated by scripts/sync-future-logs.cjs; do not edit by hand. */\n'+
  '(function(root){\n'+
  ' const verified=root.PCBL_FUTURE_GAMES='+data+';\n'+
  ' const byId=new Map((root.PCBL_VERSUS||[]).map(g=>[g.id,g]));\n'+
  ' for(const g of verified)byId.set(g.id,g);\n'+
  ' root.PCBL_VERSUS=[...byId.values()];\n'+
  '})(window);\n'};
}
async function run(){
 const config=fs.readFileSync(path.join(PUBLIC,'live-log-config.js'),'utf8');
 const endpoint=config.match(/https:\/\/script\.google\.com\/macros\/s\/[\w-]+\/exec/)?.[0];
 if(!endpoint)throw Error('Official game-log bridge is not configured');
 const saved=JSON.parse(fs.readFileSync(savedJson,'utf8'));
 const archive=JSON.parse(fs.readFileSync(path.join(PUBLIC,'versus-data.js'),'utf8').replace(/^window\.PCBL_VERSUS=/,'').replace(/;\s*$/,''));
 if(!Array.isArray(saved)||!Array.isArray(archive))throw Error('Invalid existing archive');
 const response=await fetch(endpoint+'?v='+Date.now(),{redirect:'follow',signal:AbortSignal.timeout(30000)});
 if(!response.ok)throw Error('Game-log bridge returned HTTP '+response.status);
 const reply=await response.text();
 const begin=reply.indexOf('PCBLReceiveLogTabs(');
 if(begin<0)throw Error('Game-log bridge did not return the expected callback');
 const raw=reply.slice(begin+'PCBLReceiveLogTabs('.length).trim().replace(/\);?\s*$/,'');
 const payload=JSON.parse(raw);
 if(!Array.isArray(payload.tabs))throw Error('Bridge did not include season tabs');
 const merged=parser.merge(payload,[...archive,...saved]),byId=new Map(saved.map(g=>[g.id,g]));
 const incoming=merged.games.filter(g=>/^S([4-9]|[1-9]\d{1,})$/.test(g.season));
 const problems=[];
 for(const game of incoming){
  const result=future.inspectGame(game);
  if(result.ok)byId.set(game.id,game);
  else problems.push(game.id+': '+result.issues.join('; '));
 }
 const next=[...byId.values()].sort(sort);
 const checked=play.validate([...archive,...next]);
 if(!checked.ok)throw Error('New snapshot rejected by global play registry: '+checked.issues.slice(0,5).join('; '));
 const files=render(next);
 const currentJson=fs.readFileSync(savedJson,'utf8');
 const currentJs=fs.readFileSync(savedJs,'utf8');
 const changed=currentJson!==files.json||currentJs!==files.js;
 if(changed){fs.writeFileSync(savedJson,files.json);fs.writeFileSync(savedJs,files.js);}
 console.log(JSON.stringify({status:changed?'UPDATED':'UNCHANGED',seasonTabs:payload.tabs.map(t=>t.title),futureGames:next.length,pendingGames:problems.length,bridgeIssues:merged.issues.length}));
 for(const issue of problems.slice(0,12))console.warn('Awaiting complete game log:',issue);
 for(const issue of merged.issues.slice(0,12))console.warn('Game-log parse review:',issue);
}
run().catch(error=>{console.error('Scheduled future-log import failed:',error.message);process.exitCode=1;});
