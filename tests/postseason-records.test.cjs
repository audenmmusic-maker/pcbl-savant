const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'../public');
const store=require(path.join(root,'record-store.js'));
const data=JSON.parse(fs.readFileSync(path.join(root,'data.json'),'utf8'));
const sandbox={};
(new Function('window',fs.readFileSync(path.join(root,'versus-data.js'),'utf8')))(sandbox);
globalThis.PCBL_VERSUS=sandbox.PCBL_VERSUS;
store.setOfficialProvider(()=>data);
assert.equal(store.get('Auden','S1','postseason').text,'1-2');
assert.equal(store.get('Auden','S2','postseason').text,'0-1');
assert.equal(store.get('Auden','ALL TIME','postseason').text,'1-3');
assert.equal(store.get('Jarvis','ALL TIME','postseason').text,'4-0');
assert.equal(store.get('Najee','ALL TIME','postseason').text,'1-2');
