const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'../public');
const loadJSON=name=>JSON.parse(fs.readFileSync(path.join(root,name),'utf8'));
const original=loadJSON('data.json');
const games=JSON.parse(fs.readFileSync(path.join(root,'versus-data.js'),'utf8').replace(/^window\.PCBL_VERSUS=/,'').replace(/;\s*$/,''));
const approved=require(path.join(root,'approved-corrections.js'));
const s3=src=>src.S3.find(p=>p.name==='Auden').stats.hitting;
const career=src=>src['ALL TIME'].find(p=>p.name==='Auden').stats.hitting;
test('original sheet archive is preserved, authorized Auden S3 correction is idempotent',()=>{
 assert.equal(s3(original).PA,109);
 const stats=structuredClone(original);
 const result=approved.apply(stats);
 assert.equal(result.applied,true);
 assert.equal(s3(stats).PA,92);
 assert.equal(s3(stats).AB,57);assert.equal(s3(stats).H,23);assert.equal(s3(stats).K,17);
 assert.equal(s3(stats).BB,27);assert.equal(s3(stats).HBP,8);
 assert.equal(s3(stats)['2B'],8);assert.equal(s3(stats).HR,10);
 assert.equal(s3(stats).AVG,.404);assert.equal(s3(stats).OBP,.630);
 assert.equal(s3(stats).SLG,1.070);assert.equal(s3(stats).OPS,1.700);
 assert.equal(s3(stats).PA,s3(stats).AB+s3(stats).BB+s3(stats).HBP);
 assert.equal(career(stats).PA,258);
 assert.equal(career(stats).AB,170);assert.equal(career(stats).H,59);
 assert.equal(career(stats).BB,66);assert.equal(career(stats).K,60);
 assert.equal(approved.apply(stats).approvedPA,92);
 assert.equal(career(stats).PA,258);
 assert.equal(stats.S3.find(p=>p.name==='Auden').record,'2-4');
 assert.equal(s3(original).PA,109);
});
test('confirmed six games identify 92 recorded Auden S3 PA and are pinned',()=>{
 const locked=approved.lockedGames(games);
 assert.equal(locked.ok,true);
 assert.equal(locked.byId.size,6);
 assert.equal(locked.count,92);
 const feed=structuredClone(games);
 const revised=feed.find(g=>g.id==='S3:regular:6');
 revised.events=revised.events.filter(e=>e.batter!=='Auden');
 const pinned=approved.lockGames(feed,games);
 assert.equal(pinned.ok,true);
 assert.equal(pinned.PA,92);
 const s3games=pinned.games.filter(g=>g.season==='S3'&&g.phase==='regular');
 const events=s3games.flatMap(g=>g.events.filter(e=>e.batter==='Auden'));
 assert.equal(events.length,92);
 assert.equal(pinned.games.find(g=>g.id==='S3:regular:6').events.length,games.find(g=>g.id==='S3:regular:6').events.length);
 assert.equal(feed.find(g=>g.id==='S3:regular:6').events.some(e=>e.batter==='Auden'),false);
});
test('S4 and S5 game logs are not frozen by S3 correction',()=>{
 const incoming=structuredClone(games);
 incoming.push({id:'S4:regular:1',season:'S4',stage:'regular',phase:'regular',number:1,top:'Auden',bottom:'Jarvis',score:[2,1],events:[{id:'S4:regular:1:1',batter:'Auden',pitcher:'Jarvis',inning:1,half:'top',result:'1B'}]});
 const locked=approved.lockGames(incoming,games);
 assert.equal(locked.ok,true);
 assert.ok(locked.games.some(g=>g.id==='S4:regular:1'));
});
test('approved correction matches canonical audited play data',()=>{
 const stats=structuredClone(original);approved.apply(stats);
 const context={PCBL_VERSUS:games,PCBL_SNAPSHOT:stats};
 const code=fs.readFileSync(path.join(root,'play-database.js'),'utf8');
 const out={exports:{}};
 new Function('window','module',code)(context,out);
 const db=out.exports;
 const count=db.count(db.events({season:'S3',phase:'regular',player:'Auden'}));
 assert.equal(count.PA,92);
 assert.equal(count.AB,s3(stats).AB);
 assert.equal(count.H,s3(stats).H);
 assert.equal(count.BB,s3(stats).BB);
 assert.equal(db.reconcile(stats).find(x=>x.season==='S3'&&x.player==='Auden').status,'MATCH');
});
test('live game-log loader uses approved lock and no longer references undefined accepted',()=>{
 const loader=fs.readFileSync(path.join(root,'live-logs.js'),'utf8');
 assert.match(loader,/PCBLApprovedCorrections\?\.lockGames\(result\.games,initial\)/);
 assert.ok(!loader.includes('accepted.drift'));
 assert.ok(loader.includes('check.drift'));
});
